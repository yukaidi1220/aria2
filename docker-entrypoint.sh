#!/bin/sh
# Render aria2.conf from environment variables, then exec aria2c.
#
# Variables (all optional unless noted):
#   RPC_SECRET          RPC authorization secret; must match the client
#                       (e.g. OpenList's offline download settings)
#   RPC_PORT            RPC listen port                    (default 6800)
#   DOWNLOAD_DIR        where downloads are written        (default /downloads)
#   CONF_DIR            generated config & session storage (default /config)
#   MAX_CONNECTION_PER_SERVER, MIN_SPLIT_SIZE, SPLIT, DISK_CACHE, FILE_ALLOCATION
#                       passthrough tuning knobs with sane defaults
#   EXTRA_ARIA2_OPTIONS extra aria2.conf lines, appended last so they win
#
# Anything in $CONF_DIR/aria2.conf.extra is appended after the generated
# options and can therefore override every default above.
set -eu

RPC_PORT="${RPC_PORT:-6800}"
RPC_SECRET="${RPC_SECRET:-}"
DOWNLOAD_DIR="${DOWNLOAD_DIR:-/downloads}"
CONF_DIR="${CONF_DIR:-/config}"

mkdir -p "$DOWNLOAD_DIR" "$CONF_DIR"
# Seed the session file only when missing: aria2 re-reads it on start to
# resume interrupted downloads, so it must survive container restarts.
[ -f "$CONF_DIR/aria2.session" ] || : > "$CONF_DIR/aria2.session"

conf="$CONF_DIR/aria2.conf"
cat > "$conf" <<EOF
# Generated by docker-entrypoint.sh; edits will be lost on restart.
# Use aria2.conf.extra for persistent customizations.

dir=$DOWNLOAD_DIR
continue=true
max-connection-per-server=${MAX_CONNECTION_PER_SERVER:-5}
min-split-size=${MIN_SPLIT_SIZE:-20M}
split=${SPLIT:-5}
file-allocation=${FILE_ALLOCATION:-none}
disk-cache=${DISK_CACHE:-32M}

enable-rpc=true
rpc-listen-all=true
rpc-listen-port=$RPC_PORT
rpc-secret=$RPC_SECRET

input-file=$CONF_DIR/aria2.session
save-session=$CONF_DIR/aria2.session
save-session-interval=30
EOF

if [ -n "${EXTRA_ARIA2_OPTIONS:-}" ]; then
  printf '%s\n' "$EXTRA_ARIA2_OPTIONS" >> "$conf"
fi

if [ -f "$CONF_DIR/aria2.conf.extra" ]; then
  cat "$CONF_DIR/aria2.conf.extra" >> "$conf"
fi

exec aria2c --conf-path="$conf"
